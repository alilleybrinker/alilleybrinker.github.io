export type PixelIconName = keyof typeof PIXEL_ICONS;

// The 4×4 Bayer threshold, as the field's dither uses, from 0 to 15/16.
const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];

// The icon as one path for each of the dither's 16 steps, so a reveal can
// light its pixels in the same sequence as the field's own dots.
export function pixelLayers(name: PixelIconName) {
  const layers = Array.from({ length: 16 }, () => '');
  PIXEL_ICONS[name].forEach((row, y) => {
    [...row].forEach((cell, x) => {
      if (cell === '#') layers[BAYER[(y % 4) * 4 + (x % 4)]] += `M${x} ${y}h1v1h-1z`;
    });
  });
  return layers.map((d, step) => ({ d, order: step / 16 })).filter(({ d }) => d);
}
