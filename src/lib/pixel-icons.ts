export type PixelIconName = keyof typeof PIXEL_ICONS;

// The 4×4 Bayer threshold, as the field's dither uses, from 0 to 15/16.
const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];

// Each lit pixel with its place in the dither's order, so a reveal can light
// them in the same sequence as the field's own dots.
export function pixels(name: PixelIconName) {
  return PIXEL_ICONS[name].flatMap((row, y) =>
    [...row].flatMap((cell, x) => (cell === '#' ? [{ x, y, order: BAYER[(y % 4) * 4 + (x % 4)] / 16 }] : [])),
  );
}
